-- =============================================================================
-- 관제 서버 전용 DB 계정 만들기 (MySQL 8.0). root 로 한 번만 실행한다.
--
-- 1) 아래 '여기에_비밀번호' 를 원하는 비밀번호로 바꾼다. (root 비밀번호와 다르게!)
-- 2) 실행한다.
-- 3) 같은 비밀번호를 fmsUI 폴더의 .env 파일 FMS_DB_PASSWORD 에 적는다. (.env.example 참고)
--
-- ⚠ 비밀번호를 적은 채로 이 파일을 저장 · 커밋하지 말 것. 실행한 뒤 원래대로 되돌린다.
-- 이 계정은 fms DB 의 데이터 읽기 · 쓰기만 할 수 있다 (테이블 생성 · 삭제는 root 로).
-- =============================================================================

CREATE USER IF NOT EXISTS 'fms_app'@'localhost' IDENTIFIED BY '여기에_비밀번호';
GRANT SELECT, INSERT, UPDATE, DELETE ON fms.* TO 'fms_app'@'localhost';
